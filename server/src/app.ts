import { fulfillmentRoutes } from './modules/fulfillment/fulfillment.routes.js';
import { cashierRoutes, kitchenRoutes } from './modules/orders/order.staff.routes.js';
import { operationsSettingsRoutes } from './modules/operations/operations.routes.js';
import { apiLimit } from "./middleware/rateLimits.js";
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import mongoose from 'mongoose';
import { clerkMiddleware } from '@clerk/express';
import { env, clientOrigins, serverPublishableKey } from './config/env.js';
import { authenticate } from './middleware/authenticate.js';
import { authorizeAdmin } from './middleware/authorizeAdmin.js';
import { notFound } from './middleware/notFound.js';
import { errorHandler } from './middleware/errorHandler.js';
import { AppError } from './utils/errors.js';
import { publicSettings } from './utils/fulfillment.js';
import { webhookRoutes } from './modules/webhooks/webhook.routes.js';
import { menuRoutes, adminMenuRoutes } from './modules/menu/menu.routes.js';
import { orderRoutes, adminOrderRoutes } from './modules/orders/order.routes.js';
import { reservationRoutes, adminReservationRoutes } from './modules/reservations/reservation.routes.js';
import { userRoutes } from './modules/users/user.routes.js';
import { Order } from './modules/orders/order.model.js';
import { Reservation } from './modules/reservations/reservation.model.js';
import { Menu } from './modules/menu/menu.model.js';
export const app = express();
app.disable('x-powered-by');
// Render has one trusted reverse proxy; do not blindly trust all forwarded IPs.
if (env.NODE_ENV === 'production') app.set('trust proxy', 1);
app.use(helmet());
app.use(cors({ origin(origin, callback) { if (!origin || clientOrigins.includes(origin)) callback(null, true); else callback(new AppError(403, 'ORIGIN_FORBIDDEN', 'Origin is not allowed.')); }, methods: ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'], allowedHeaders: ['Authorization', 'Content-Type', 'Idempotency-Key'], credentials: false }));
app.get('/health', (_req, res) => { const connected = mongoose.connection.readyState === 1; res.status(connected ? 200 : 503).json({ data: { status: connected ? 'ok' : 'unavailable', database: connected ? 'connected' : 'disconnected' } }); });
// Raw signed webhook must precede JSON parsing and Clerk authentication.
app.use('/api/webhooks', webhookRoutes);
app.use(express.json({ limit: '64kb', strict: true }));
app.use('/api/v1', apiLimit);
app.use('/api/v1', (_req, res, next) => { res.set('Cache-Control', 'no-store'); next(); });
app.get('/api/v1/settings', async (_req, res) => res.json({ data: await publicSettings() }));
app.use('/api/v1/menu', menuRoutes);
if (serverPublishableKey && clientOrigins.length) app.use(clerkMiddleware({ secretKey: env.CLERK_SECRET_KEY, publishableKey: serverPublishableKey, authorizedParties: clientOrigins }));
app.use('/api/v1/users', authenticate, userRoutes);
app.use('/api/v1/orders', authenticate, orderRoutes);
app.use('/api/v1/reservations', authenticate, reservationRoutes);
app.use('/api/v1/staff/orders', authenticate, cashierRoutes);
app.use('/api/v1/kitchen/orders', authenticate, kitchenRoutes);
app.use('/api/v1/admin', authenticate, authorizeAdmin);
app.use('/api/v1/admin/operations-settings', operationsSettingsRoutes);
app.use('/api/v1/admin/fulfillment-settings', fulfillmentRoutes);
app.get('/api/v1/admin/overview', async (_req, res) => { const [orders, reservations, menuItems, recentOrders] = await Promise.all([Order.countDocuments(), Reservation.countDocuments(), Menu.countDocuments({ archived: false }), Order.find().sort({ createdAt: -1 }).limit(5).select('orderNumber customer.name status totalHalalas createdAt')]); res.json({ data: { orders, reservations, menuItems, recentOrders } }); });
app.use('/api/v1/admin/menu', adminMenuRoutes);
app.use('/api/v1/admin/orders', adminOrderRoutes);
app.use('/api/v1/admin/reservations', adminReservationRoutes);
app.use(notFound);
app.use(errorHandler);
