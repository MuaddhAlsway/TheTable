import { createPaymentSession } from '../payments/payment.service.js';
import { userId } from '../../middleware/authenticate.js';
import { input } from '../../middleware/validateRequest.js';
import { Router } from 'express';
import { z } from 'zod';
import { objectId } from '../../utils/validation.js';
import { validateRequest as validate } from '../../middleware/validateRequest.js';
import { creationLimit, staffMutationLimit } from '../../middleware/rateLimits.js';
import { orderInput, orderQuery, orderStatusInput } from './order.validation.js';
import * as controller from './order.controller.js';
const id = validate(z.object({ id: objectId }), 'params');
export const orderRoutes = Router();
orderRoutes.post('/', creationLimit, validate(orderInput), controller.create);
orderRoutes.get('/', validate(orderQuery, 'query'), controller.mine);
orderRoutes.post('/:id/payment-session', creationLimit, id, validate(z.object({}).strict()), async (req, res) => { res.json({ data: await createPaymentSession(input<{ id: string }>(res, 'params').id, userId(req), req.header('origin')) }); });
orderRoutes.get('/:id', id, controller.myDetail);
export const adminOrderRoutes = Router();
adminOrderRoutes.get('/', validate(orderQuery, 'query'), controller.adminList);
adminOrderRoutes.get('/:id', id, controller.adminDetail);
adminOrderRoutes.patch('/:id/status', staffMutationLimit, id, validate(orderStatusInput), controller.status);
