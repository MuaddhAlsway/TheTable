import { readyEstimateInput, updateReadyEstimate } from './order.estimates.js';
import { input } from '../../middleware/validateRequest.js';
import { actor } from '../../utils/roles.js';
import { staffOrderDTO } from './order.operations.js';
import { getOperations } from '../operations/operations.service.js';
import { Router } from 'express';
import { z } from 'zod';
import { objectId, pagination } from '../../utils/validation.js';
import { validateRequest as validate } from '../../middleware/validateRequest.js';
import { authorizeRoles } from '../../middleware/authorizeRoles.js';
import { staffMutationLimit } from '../../middleware/rateLimits.js';
import { orderQuery, orderActionInput } from './order.validation.js';
import * as controller from './order.controller.js';
const id = validate(z.object({ id: objectId }).strict(), 'params');
const mutate = [staffMutationLimit, id, validate(orderActionInput)];
export const cashierRoutes = Router();
cashierRoutes.use(authorizeRoles('admin', 'cashier'));
cashierRoutes.post('/:id/ready-estimate', staffMutationLimit, id, validate(readyEstimateInput), async (_req, res) => { const order = await updateReadyEstimate(input<{ id: string }>(res, 'params').id, input(res), actor(res)); res.json({ data: staffOrderDTO(order, actor(res).role, await getOperations()) }); });
cashierRoutes.get('/', validate(orderQuery, 'query'), controller.cashierList);
cashierRoutes.get('/:id', id, controller.adminDetail);
cashierRoutes.post('/:id/accept', ...mutate, controller.orderAction('accept'));
cashierRoutes.post('/:id/reject', ...mutate, controller.orderAction('reject'));
cashierRoutes.post('/:id/cancel', ...mutate, controller.orderAction('cancel'));
cashierRoutes.post('/:id/complete-pickup', ...mutate, controller.orderAction('complete_pickup'));
cashierRoutes.post('/:id/dispatch-delivery', ...mutate, controller.orderAction('dispatch_delivery'));
cashierRoutes.post('/:id/complete-delivery', ...mutate, controller.orderAction('complete_delivery'));
const kitchenQuery = z.object({ ...pagination, status: z.enum(['confirmed', 'preparing', 'ready_for_pickup', 'ready_for_delivery']).optional(), fulfillment: z.enum(['delivery', 'pickup']).optional(), orderNumber: z.string().trim().max(60).optional() }).strict();
export const kitchenRoutes = Router();
kitchenRoutes.use(authorizeRoles('admin', 'kitchen'));
kitchenRoutes.get('/', validate(kitchenQuery, 'query'), controller.kitchenList);
kitchenRoutes.post('/:id/start', ...mutate, controller.orderAction('start_preparation'));
kitchenRoutes.post('/:id/ready', ...mutate, controller.orderAction('mark_ready'));
