import { Router } from 'express';
import { z } from 'zod';
import { objectId } from '../../utils/validation.js';
import { validateRequest as validate } from '../../middleware/validateRequest.js';
import { creationLimit, staffMutationLimit } from '../../middleware/rateLimits.js';
import { authorizeRoles } from '../../middleware/authorizeRoles.js';
import { reservationInput, reservationQuery, reservationStatusInput, reservationCancelInput } from './reservation.validation.js';
import * as controller from './reservation.controller.js';
const id = validate(z.object({ id: objectId }), 'params');
export const reservationRoutes = Router();
reservationRoutes.post('/', creationLimit, validate(reservationInput), controller.create);
reservationRoutes.get('/', validate(reservationQuery, 'query'), controller.mine);
reservationRoutes.get('/:id', id, controller.myDetail);
reservationRoutes.post('/:id/cancel', creationLimit, id, validate(reservationCancelInput), controller.cancel);
export const adminReservationRoutes = Router();
adminReservationRoutes.get('/', validate(reservationQuery, 'query'), controller.adminList);
adminReservationRoutes.patch('/:id/status', staffMutationLimit, id, validate(reservationStatusInput), controller.status);
export const staffReservationRoutes = Router();
staffReservationRoutes.use(authorizeRoles('admin', 'cashier'));
staffReservationRoutes.get('/', validate(reservationQuery, 'query'), controller.adminList);
staffReservationRoutes.patch('/:id/status', staffMutationLimit, id, validate(reservationStatusInput), controller.status);
